/**
 * Рекомендация длительности — из истории человека, не из вкуса дизайнера.
 *
 * Default Effect здесь работает КАК ПОДДЕРЖКА, а не как способ вытянуть из
 * человека обещание побольше. Разница видна в одном правиле: 45 минут не
 * становятся дефолтом никогда, ни при какой истории. Продукт может
 * предложить подняться с 15 на 25, когда данные это оправдывают, но не
 * может подтолкнуть к длительности, ранний выход из которой ощущается
 * провалом — а именно так работают 45 минут для человека, который
 * пришёл сюда потому, что ему трудно начинать.
 *
 * Все выводы строятся на `minutes` из StartEntry — это РЕАЛЬНО отработанные
 * минуты, а не заказанные. Заказанную длительность память не хранит, и
 * додумывать её нельзя: рекомендация, построенная на выдуманном поле, врёт
 * тем убедительнее, чем аккуратнее выглядит.
 */

import type { StartEntry } from '@/lib/memory'

export const DURATIONS = [15, 25, 45] as const
export type Duration = (typeof DURATIONS)[number]

/** Смысловые подписи вместо голых цифр (#33). */
export const DURATION_LABEL: Record<Duration, string> = {
  15: 'Мягкий вход',
  25: 'Устойчивый блок',
  45: 'Глубже в дело',
}

/** Сессия, доведённая хотя бы до пятнадцати минут, считается состоявшейся. */
const FULL_BLOCK_MIN = 14
/** Меньше десяти минут — человек вышел рано. Это не провал, это данные. */
const EARLY_EXIT_MAX = 10

export type DurationAdvice = {
  minutes: Duration
  /**
   * Честное объяснение рекомендации (#35). Confirmation bias здесь
   * подтверждает разумность маленького шага фактом из истории, а не
   * бессодержательной похвалой: «тебе это подходит» без причины —
   * лесть, и человек это чувствует.
   * null — объяснять нечего (нет истории), и врать не нужно.
   */
  reason: string | null
}

export function recommendDuration(starts: StartEntry[]): DurationAdvice {
  if (starts.length === 0) {
    return {
      minutes: 15,
      reason: 'Начнём с малого — пятнадцать минут ни к чему не обязывают.',
    }
  }

  const recent = starts.slice(-5)
  const lastThree = starts.slice(-3)

  const earlyExits = lastThree.filter((s) => s.minutes < EARLY_EXIT_MAX).length
  if (earlyExits >= 2) {
    return {
      minutes: 15,
      reason: 'Последние разы выходили рано — возьмём короче, так проще вернуться.',
    }
  }

  const fullBlocks = recent.filter((s) => s.minutes >= FULL_BLOCK_MIN).length
  if (fullBlocks >= 2) {
    return {
      minutes: 25,
      reason: 'Короткие блоки давались тебе легко — двадцать пять уже по силам.',
    }
  }

  return {
    minutes: 15,
    reason: 'Пятнадцать минут подойдут сейчас: короткий старт легче начать.',
  }
}

/**
 * Формулировка «сколько это стоит» рядом с задачей.
 * «результат не обязателен» — не украшение: это снятие условия, из-за
 * которого человек не начинает. Обещание не закончить дело, а побыть с ним.
 */
export function durationContract(minutes: number): string {
  return `${minutes} минут · результат не обязателен`
}
