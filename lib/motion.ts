/**
 * Хореография входа экрана (#27): не один общий app-page-in на всю
 * страницу, а лестница — фон, потом контекст, потом контент, потом
 * управление. Разница в 60мс между соседями не читается как «анимация»,
 * но глаз получает порядок чтения даром: что важно — приходит первым.
 * Держим лестницу короткой: полный вход укладывается в ~300мс из
 * энциклопедии, дальше пользователь уже ждёт.
 */
export const STAGGER_STEP = 0.06;

/** Задержка n-го элемента лестницы входа. */
export function stagger(index: number, base = 0): number {
  return base + index * STAGGER_STEP;
}
