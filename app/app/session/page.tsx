import type { Metadata } from 'next'
import { Suspense } from 'react'
import { FocusSession } from '@/components/focus-session'

export const metadata: Metadata = {
  title: 'Фокус — Напарник',
  description: 'Фокус-сессия вдвоём с напарником. Старт засчитывается сразу.',
}

export default function SessionPage() {
  return (
    /*
     * h-dvh + overflow-hidden + pb-20 — тот же приём, что уже работает на
     * /app/page.tsx, и по той же причине.
     *
     * Что было: min-h-dvh + pb-16 позволяет странице расти ЕСТЕСТВЕННЫМ
     * document-flow скроллом за пределы вьюпорта. Отступ pb-* в таком
     * контейнере добавляет место ПОСЛЕ всего контента, в самом низу
     * документа — он не отодвигает то, что уже поместилось в первый экран,
     * от нижней кромки. AppNav — fixed и всегда сидит в нижних 69px
     * реального вьюпорта независимо от скролла; кнопка сетапа физически
     * помещалась в эти первые 844px (высота её контента меньше вьюпорта) и
     * потому перекрывалась таббаром на первом кадре — до всякого скролла,
     * который тут и не требовался бы, чтобы её увидеть.
     * Замерено рендером: при min-h-dvh добавление pb-16→pb-24 честно
     * увеличивало scrollHeight документа на 32px, но координаты самой
     * кнопки относительно вьюпорта не менялись ни на пиксель.
     *
     * Фикс — не в отступе, а в модели контейнера: h-dvh фиксирует высоту
     * <main> РОВНО во вьюпорт, pb-20 вычитается ИЗНУТРИ этой фиксированной
     * высоты (а не пристёгивается сверх неё), гарантируя нижние 80px
     * пустыми независимо от контента. overflow-hidden запрещает контенту
     * тихо вылезать в эту зону; FocusSession получает собственный
     * overflow-y-auto на каждой фазе, чтобы длинный контент (раскрытое
     * дробление, лист завершения) скроллился ВНУТРИ отведённой высоты, а
     * не раздвигал документ.
     */
    <main className="app-page-enter flex h-dvh flex-col overflow-hidden pb-20">
      <Suspense fallback={null}>
        <FocusSession />
      </Suspense>
    </main>
  )
}
